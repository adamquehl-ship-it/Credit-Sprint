/* Builds a course's key-term questions from its flashcards: node scripts/gen-terms.js aplit
   Every card becomes "Which term fits this description?" with three wrong terms from the same unit,
   and every third card also gets the reverse ("What does ___ mean?"). Seeded, so the output is stable
   (question ids are positions, so a stable order keeps students' mistake lists valid). */
const fs = require("fs"), path = require("path");
const k = process.argv[2]; if (!k) { console.error("usage: node scripts/gen-terms.js <course folder>"); process.exit(1); }
const dir = path.join(__dirname, "..", "assets", "data", k);
global.window = {};
for (const f of ["cards.js", "cards2.js"]) { const p = path.join(dir, f); if (fs.existsSync(p)) eval(fs.readFileSync(p, "utf8")); }
const cards = window.CS_CARDS_RAW || [];
let h = 2166136261; for (const c of "terms-" + k) { h ^= c.charCodeAt(0); h = Math.imul(h, 16777619); }
const rnd = () => { h ^= h << 13; h ^= h >>> 17; h ^= h << 5; return ((h >>> 0) % 1e6) / 1e6; };
const shuffle = a => { a = a.slice(); for (let i = a.length - 1; i > 0; i--) { const j = Math.floor(rnd() * (i + 1)); [a[i], a[j]] = [a[j], a[i]]; } return a; };
const lc = s => s.charAt(0).toLowerCase() + s.slice(1);
const trim = s => s.replace(/\.$/, "");
const out = [];
cards.forEach((c, i) => {
  const [u, term, def] = c;
  /* best distractors first: terms that share a key word (tone, imagery, sonnet, irony...), then the same unit, then the rest */
  const words = t => (t.toLowerCase().match(/[a-z]{4,}/g) || []).filter(w => !["with","that","from","into","person","point","view"].includes(w));
  const kin = x => words(x[1]).some(w => words(term).includes(w));
  const same = cards.filter(x => x !== c && x[1] !== term);
  const pool = shuffle(same.filter(kin)).concat(shuffle(same.filter(x => !kin(x) && x[0] === u)), shuffle(same.filter(x => !kin(x) && x[0] !== u)));
  const wrong = pool.slice(0, 3);
  out.push([u, `Which term best fits this description: ${lc(trim(def))}?`, [term, `${term}: ${def}`], wrong.map(w => [w[1], `${w[1]} means something else: ${lc(w[2])}`])]);
  if (i % 3 === 1) {
    const wd = pool.slice(3, 6);
    out.push([u, `Which statement best describes ${/^[A-Z]{2}/.test(term) ? term : lc(term)}?`, [def, `That is the meaning of ${lc(term)}.`], wd.map(w => [w[2], `That describes ${lc(w[1])}, not ${lc(term)}.`])]);
  }
});
const js = `/* Generated by scripts/gen-terms.js from this course's flashcards. Do not edit by hand. */\n(function(){var a=${JSON.stringify(out)};\nwindow.CS_QUESTIONS_RAW=(window.CS_QUESTIONS_RAW||[]).concat(a)})();\n`;
fs.writeFileSync(path.join(dir, "terms.js"), js);
console.log(`${k}: ${out.length} key-term questions from ${cards.length} cards`);
